type Fn = (...m: string[]) => string;
/** جمل متغيرة لا تُكتب في الكود (أغلبها رسائل الخادم) */
export const EN_PATTERNS: [RegExp, string | Fn][] = [
  // عنوان متبوع بعدد بين قوسين، مثل «بنود المصروفات (35)»
  [/^(.*\S) \((\d+)\)$/, (whole, t, n) => (EN_UI[t] != null ? `${EN_UI[t]} (${n})` : whole)],
  [/^محاولات خاطئة كثيرة\. حاول بعد (\d+) دقيقة$/, (_, n) => `Too many wrong attempts. Try again in ${n} minutes`],
  [/^تعذر تحليل الفاتورة: (.*)$/, (_, r) => `Couldn't analyze the receipt: ${translateServer(r)}`],
  [/^خدمة التحليل عند جوجل مزدحمة الآن\. حاول بعد دقيقة أو أدخل البيانات يدوياً\. \((.*)\)$/, (_, d) => `Google's analysis service is busy right now. Try in a minute or enter the data manually. (${d})`],
  [/^خدمة التحليل رفضت الطلب \((\d+)\): (.*)$/, (_, c, d) => `The analysis service rejected the request (${c}): ${d}`],
  [/^لم يُرجع النموذج نصاً \((.*)\)$/, (_, r) => `The model returned no text (${r === 'بلا سبب' ? 'no reason' : r})`],
  [/^تعذرت قراءة الفاتورة\. حاول بصورة أوضح\. \((.*)\)$/, (_, d) => `Couldn't read the receipt. Try a clearer photo. (${d})`],
];

function translateServer(s: string): string {
  if (EN_UI[s] != null) return EN_UI[s];
  for (const [re, fn] of EN_PATTERNS) { const m = s.match(re); if (m) return typeof fn === 'function' ? fn(...m) : fn; }
  return s;
}
